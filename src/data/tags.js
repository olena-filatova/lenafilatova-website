//
// WHY THIS IS NOT IN blog.js. Two reasons. blog.js is 10k lines and every new
// post lands at the top of it, so per-post `tags: []` would put a tagging edit
// in the middle of the file every open PR is already touching. And the list
// below is the thing Lena reviews — a vocabulary reads as a vocabulary here,
// and as 52 scattered array literals there.
//
// EDITING. `posts` is an ordered list of blog.js slugs, newest first. Renaming
// a key changes a live URL, so redirect it rather than editing in place; adding
// or removing a slug is free. tags-lib.js fails the build on a slug that does
// not exist, so a typo or a deleted post can't silently empty a tag page.
//
// PROVENANCE. The first pass was generated by matching each tag's vocabulary
// across every article's title, standfirst, body and FAQ, then reviewed. That
// pass is why a few assignments look incidental (`hrt` catches the
// perimenopause/diabetes explainer because it discusses hormone therapy at
// length) — those are correct, but this file is meant to be corrected by hand
// where they are not.
//
// TAGS vs CATS. Tags are deliberately narrower than the six `cats` in
// blog-lib.js, which are the Journal's filter chips. A tag that lands on half
// the archive is a category wearing a tag's clothes and filters nothing.

